def _rules_block(style_rules: list[str], recent_posts: list[str]) -> str:
    parts = []
    if style_rules:
        parts.append("ПРАВИЛА СТИЛЯ (обязательны):\n" + "\n".join(f"- {r}" for r in style_rules))
    if recent_posts:
        examples = "\n\n---\n\n".join(p[:1200] for p in recent_posts[:3])
        parts.append(
            "ПРИМЕРЫ УДАЧНЫХ ПОСТОВ (ориентир по голосу, не копировать):\n\n" + examples
        )
    return "\n\n".join(parts)


def strategy_user(brief: dict[str, Any], style_rules: list[str], recent_posts: list[str]) -> str:
    return (
        "БРИФ:\n" + json.dumps(brief, ensure_ascii=False, indent=2)
        + "\n\n" + _rules_block(style_rules, recent_posts)
        + "\n\nСначала выбери угол, который реально решает цель. Верни JSON по схеме."
    )


def copy_user(
    brief: dict[str, Any],
    strategy: dict[str, Any],
    style_rules: list[str],
    recent_posts: list[str],
    has_images: bool,
    channels: list[str],
) -> str:
    return (
        "БРИФ:\n" + json.dumps(brief, ensure_ascii=False, indent=2)
        + "\n\nСТРАТЕГИЯ:\n" + json.dumps(strategy, ensure_ascii=False, indent=2)
        + f"\n\nКАРТИНКИ: {'есть' if has_images else 'нет, нужен процедурный арт'}"
        + f"\nКАНАЛЫ: {', '.join(channels)}"
        + "\n\n" + _rules_block(style_rules, recent_posts)
        + "\n\nНапиши финальные тексты, самопроверься по рубрике и верни JSON по схеме."
    )
